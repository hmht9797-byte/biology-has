def activity(ch):
    kind, title, items = ACT[ch]
    if kind == 'match':
        import random
        rng = random.Random(ch * 7)
        right = [b for _, b in items]; order = list(range(4)); rng.shuffle(order)
        if order == list(range(4)): order = order[::-1]
        rows = ''.join(f'<tr><td><b>{n+1}-</b> {a}</td><td class="dots"></td><td><b>{LETTERS[k]}-</b> {right[order[k]]}</td></tr>' for n,(a,_) in enumerate(items) for k in [n])
        ans = '   '.join(f'({n+1}) {LETTERS[order.index(n)]}' for n in range(4))
        body = f'<table class="fl-match">{rows}</table>'
    else:
        rows = ''.join(f'<li><span class="tfbox"></span>{s}</li>' for s,_ in items)
        ans = '، '.join(f'{n+1}: {"صح" if v else "خطأ"}' for n,(_,v) in enumerate(items))
        body = f'<ol class="fl-tf">{rows}</ol>'
    return f'''<div class="fl-act avoid"><div class="fl-act-h"><span class="fl-badge">نشاط ممتع</span> {title}</div>{body}
<div class="fl-ans">الإجابة: {ans}</div></div>'''

def quote(i):
    q = QUOTES[i % len(QUOTES)]
    return f'''<div class="fl-quote avoid"><svg width="34" height="28" viewBox="0 0 34 28"><path d="M0 28V16C0 6 6 1 14 0l1 4c-5 2-7 5-7 10h7v14zm19 0V16c0-10 6-15 14-16l1 4c-5 2-7 5-7 10h7v14z" fill="currentColor" opacity=".35"/></svg><span>{q}</span></div>'''

def notes(h):
    return f'<div class="fl-notes avoid" style="height:{h:.0f}mm"><div class="fl-notes-t">ملاحظاتي</div></div>'

# approximate block heights in mm (incl. margins)
H_DYK, H_ACT, H_Q = 34, 72, 22

USED=set()
def make(ch, idx, gap):
    """return html that fits within gap (mm)"""
    g = gap - 6   # safety
    out = []
    if ch == 0 or g < 18:
        return ''
    act_ok = ch in ACT and ch not in USED
    if g >= H_ACT + H_DYK + 8 and act_ok:
        USED.add(ch)
        out += [activity(ch), dyk(ch, idx)]; g -= H_ACT + H_DYK
    elif g >= H_ACT + 4 and act_ok and g < H_ACT + H_DYK + 8:
        USED.add(ch)
        out += [activity(ch)]; g -= H_ACT
    elif g >= H_DYK + 4:
        out += [dyk(ch, idx)]; g -= H_DYK
    if g >= H_Q + 26:
        out += [notes(g - 4)]
    elif g >= H_Q + 2:
        out += [quote(idx)]
    return '<div class="fl-wrap">' + ''.join(out) + '</div>' if out else ''
